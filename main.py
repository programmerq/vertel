import os
import sqlite3
import git
import re


def initialize_database(db_path):
    conn = sqlite3.connect(db_path)
    cursor = conn.cursor()
    cursor.execute('''CREATE TABLE IF NOT EXISTS file_index (
                        id INTEGER PRIMARY KEY,
                        tag TEXT,
                        file_path TEXT,
                        line_number INTEGER,
                        UNIQUE(tag, file_path, line_number))''')
    cursor.execute('''CREATE INDEX IF NOT EXISTS idx_file_line_tag ON file_index (file_path, line_number, tag)''')
    conn.commit()
    conn.close()

